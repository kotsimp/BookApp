"""
format_sync.py - Keeps format-preserved outputs safe when their plain-text translation changes.

In-place DOCX/EPUB translations and translated comics must never be regenerated from plain text: that would discard
styles, tables, images, CSS or artwork.

* `protected_files()` says which outputs of a job those are (marker file written by the pipeline, with conservative
  detection for outputs created before the marker existed).
* `sync_text()` carries text edits (editor, AI Polish) into those DOCX/EPUB files: only the edited characters change.
  It is all-or-nothing: if an edit cannot be placed safely, `FormatSyncError` is raised and nothing is written.

Mapping: the plain-text translation holds one paragraph per translated block of the document, with the same
non-whitespace characters. Edits are found between the old and the new text and mapped onto the document's text
nodes through those characters, so whitespace that differs between the two never matters.
"""

import copy
import difflib
import io
import json
import logging
import os
import posixpath
import re
import uuid
import zipfile
from collections import Counter
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple
from urllib.parse import unquote

logger = logging.getLogger(__name__)

MARKER_NAME = ".format_preserved.json"
COMIC_SUFFIXES = {".pdf", ".cbz", ".cbr", ".epub"}

_PARA_SPLIT_RE = re.compile(r"\n[^\S\n]*\n\s*")
_PAGE_MARKER_RE = re.compile(r"^=== PAGE \d+ ===[ \t]*$", re.MULTILINE)
_TOKEN_RE = re.compile(r"\s+|\w+|[^\w\s]")
_XML_INVALID_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\ud800-\udfff￾￿]")


class FormatSyncError(RuntimeError):
    """An edit could not be applied to a format-preserved document; no file was changed."""


# ---------------------------------------------------------------------------
# Which outputs are format-preserved
# ---------------------------------------------------------------------------

def _read_marker(out_dir: Path) -> Dict[str, bool]:
    try:
        data = json.loads((out_dir / MARKER_NAME).read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def mark_output(path, preserved: bool) -> None:
    """Records how the translation pipeline produced `path`."""
    p = Path(path)
    tmp = p.parent / f"{MARKER_NAME}.{uuid.uuid4().hex[:8]}.tmp"
    try:
        data = _read_marker(p.parent)
        data[p.name] = bool(preserved)
        tmp.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
        os.replace(tmp, p.parent / MARKER_NAME)
    except OSError as e:  # never fail a finished translation over this; detection then falls back to inspection
        logger.warning(f"Could not record how {p.name} was produced: {e}")
        tmp.unlink(missing_ok=True)


def is_comic_output(job, out_dir: Path) -> bool:
    if (Path(out_dir) / ".comic_vision_checkpoint.json").exists():
        return True
    return bool(job and (
        (getattr(job, "layout_mode", "") or "") in ("comic", "graphic_novel")
        or (getattr(job, "file_type", "") or "").lower() in ("cbz", "cbr")
    ))


def _made_by_exporter(path: Path, source: Optional[Path]) -> bool:
    """For unmarked files: True only when the file was clearly generated from plain text by backend.exporter."""
    try:
        if path.suffix.lower() == ".docx":
            import docx
            default_note = "generated by python-docx"
            if docx.Document(str(path)).core_properties.comments != default_note:
                return False
            if not source or not source.is_file():
                return False
            return docx.Document(str(source)).core_properties.comments != default_note
        from ebooklib import epub
        ids = [v for v, _attrs in epub.read_epub(str(path)).get_metadata("DC", "identifier")]
        return path.stem in ids  # export_epub uses the file stem as the book identifier
    except Exception as e:
        logger.warning(f"Could not tell how {path.name} was produced ({e}); treating it as format-preserved.")
        return False


def protected_files(job, out_dir) -> Set[Path]:
    """Existing outputs of a job that must never be regenerated from plain text."""
    out_dir = Path(out_dir)
    if not out_dir.is_dir():
        return set()
    marker = _read_marker(out_dir)
    comic = is_comic_output(job, out_dir)
    src_ext = f".{(getattr(job, 'file_type', '') or '').lower()}" if job else ""
    source = Path(job.file_path) if job and getattr(job, "file_path", "") else None

    found: Set[Path] = set()
    for f in out_dir.iterdir():
        if not f.is_file():
            continue
        ext = f.suffix.lower()
        if comic and ext in COMIC_SUFFIXES:
            found.add(f)
        elif f.name in marker:
            if marker[f.name]:
                found.add(f)
        elif ext in (".docx", ".epub") and ext == src_ext and "_translated_" in f.name:
            if not _made_by_exporter(f, source):
                found.add(f)
    return found


# ---------------------------------------------------------------------------
# Mapping edits onto text nodes
# ---------------------------------------------------------------------------

def _key(text: str) -> str:
    return "".join(text.split())


def split_paragraphs(text: str) -> List[str]:
    body = _PAGE_MARKER_RE.sub("", (text or "").replace("\r\n", "\n").replace("\r", "\n"))
    return [p.strip() for p in _PARA_SPLIT_RE.split(body) if p.strip()]


def _matcher(a, b) -> difflib.SequenceMatcher:
    return difflib.SequenceMatcher(None, a, b, autojunk=False)


def edit_nodes(nodes: List[str], old: str, new: str) -> List[str]:
    """Applies the edit `old` -> `new` to the text nodes of one block, keeping each node's formatting."""
    doc = "".join(nodes)
    if _key(doc) != _key(old):
        raise FormatSyncError("paragraph does not match the document")
    old_pos = [i for i, c in enumerate(old) if not c.isspace()]
    doc_pos = [i for i, c in enumerate(doc) if not c.isspace()]

    def to_doc(offset: int) -> int:
        seen = len([p for p in old_pos if p < offset])
        old_prev = old_pos[seen - 1] + 1 if seen else 0
        doc_prev = doc_pos[seen - 1] + 1 if seen else 0
        doc_next = doc_pos[seen] if seen < len(doc_pos) else len(doc)
        if seen < len(old_pos) and offset == old_pos[seen]:
            return doc_next
        return min(doc_prev + (offset - old_prev), doc_next)

    a, b = _TOKEN_RE.findall(old), _TOKEN_RE.findall(new)
    starts = [0]
    for tok in a:
        starts.append(starts[-1] + len(tok))

    out = list(nodes)
    bounds = [0]
    for n in nodes:
        bounds.append(bounds[-1] + len(n))

    # right to left, so offsets of edits still to come stay valid
    for op, i1, i2, j1, j2 in reversed(_matcher(a, b).get_opcodes()):
        if op == "equal" or not nodes:
            continue
        repl = "".join(b[j1:j2])
        start = to_doc(starts[i1])
        end = max(start, to_doc(starts[i2]))
        if start < end:  # replacement: takes the formatting of the first replaced character
            owner = next(k for k in range(len(nodes)) if bounds[k] <= start < bounds[k + 1])
        else:  # insertion: continues the preceding text, unless it is a word typed in front of the next one
            before = next((k for k in range(len(nodes)) if bounds[k] < start <= bounds[k + 1]), None)
            after = next((k for k in range(len(nodes)) if bounds[k] <= start < bounds[k + 1]), None)
            prefixes_next = repl[-1:].isspace() and not repl[:1].isspace()
            owner = after if (after is not None and (before is None or prefixes_next)) else (before or 0)
        for k in range(len(nodes) - 1, -1, -1):
            lo, hi = max(start, bounds[k]), min(end, bounds[k + 1])
            cut_from, cut_to = lo - bounds[k], hi - bounds[k]
            if k == owner:
                cut_to = max(cut_to, cut_from)
                out[k] = out[k][:cut_from] + repl + out[k][cut_to:]
            elif lo < hi:
                out[k] = out[k][:cut_from] + out[k][cut_to:]
    return out


def _plan(block_texts: List[str], old_text: str, new_text: str) -> List[Tuple]:
    """
    Turns a text change into block operations:
    ("edit", block, old_para, new_para) | ("delete", block) |
    ("insert", anchor_block, before?, [paragraphs], at_end?).
    """
    old, new = split_paragraphs(old_text), split_paragraphs(new_text)
    old_keys = [_key(p) for p in old]

    block_keys = [_key(t) for t in block_texts]
    in_order: Dict[int, int] = {}
    for m in _matcher(old_keys, block_keys).get_matching_blocks():
        for k in range(m.size):
            in_order[m.a + k] = m.b + k
    # A paragraph may sit elsewhere in the document (DOCX text lists table cells last, so text appended after them
    # lives earlier, in the body): also pair leftovers whose content occurs exactly once on each side.
    block_of = dict(in_order)
    free: Dict[str, List[int]] = {}
    for j in sorted(set(range(len(block_keys))) - set(in_order.values())):
        free.setdefault(block_keys[j], []).append(j)
    loose = [i for i in range(len(old)) if i not in in_order]
    loose_count = Counter(old_keys[i] for i in loose)
    for i in loose:
        if loose_count[old_keys[i]] == 1 and len(free.get(old_keys[i], ())) == 1:
            block_of[i] = free[old_keys[i]][0]
    claimed = set(block_of.values())

    def mapped(i: int, step: int, where: Dict[int, int] = block_of) -> Optional[int]:
        while 0 <= i < len(old):
            if i in where:
                return where[i]
            i += step
        return None

    def block(i: int) -> Optional[int]:
        """
        The block of paragraph i. None for text the document does not hold (EPUB navigation entries: regenerated
        on save). Anything else that does not match means the two drifted apart, and editing would be guesswork.
        """
        if i in block_of:
            return block_of[i]
        before, after = mapped(i - 1, -1, in_order), mapped(i + 1, 1, in_order)
        gap_start = 0 if before is None else before + 1
        gap_end = len(block_texts) if after is None else after
        if any(j not in claimed for j in range(gap_start, gap_end)):
            raise FormatSyncError(f"paragraph {i + 1} has no counterpart in the document")
        return None

    ops: List[Tuple] = []
    for tag, i1, i2, j1, j2 in _matcher(old, new).get_opcodes():
        if tag == "equal":
            continue
        n_old, n_new = i2 - i1, j2 - j1
        pairs = min(n_old, n_new)
        shift_old = shift_new = 0
        if pairs and n_old != n_new:
            # paragraphs added/removed next to edited ones: pair each edit with the paragraph it resembles most
            def score(s: int) -> float:
                return sum(_matcher(old[i1 + k + (s if n_old > n_new else 0)],
                                    new[j1 + k + (s if n_new > n_old else 0)]).quick_ratio() for k in range(pairs))
            shift = max(range(abs(n_old - n_new) + 1), key=score)
            shift_old, shift_new = (shift, 0) if n_old > n_new else (0, shift)

        for k in range(pairs):
            o, n = i1 + shift_old + k, j1 + shift_new + k
            if old[o] != new[n]:
                target = block(o)
                if target is not None:
                    ops.append(("edit", target, old[o], new[n]))
        for o in range(i1, i2):
            if not (i1 + shift_old <= o < i1 + shift_old + pairs):
                target = block(o)
                if target is not None:
                    ops.append(("delete", target))

        head = new[j1:j1 + shift_new]
        tail = new[j1 + shift_new + pairs:j2]
        for paras, at in ((head, i1 + shift_old), (tail, i1 + shift_old + pairs)):
            if not paras:
                continue
            preceding, following = mapped(at - 1, -1), mapped(at, 1)
            if at > 0:
                block(at - 1)  # refuses when the text around the insertion has drifted from the document
            if preceding is not None:
                ops.append(("insert", preceding, False, paras, following is None))
            elif following is not None:
                ops.append(("insert", following, True, paras, False))
            else:
                raise FormatSyncError("the document has no paragraph to attach new text to")
    # insertions first (their anchors must still be attached), deletions last
    return sorted(ops, key=lambda op: ("insert", "edit", "delete").index(op[0]))


