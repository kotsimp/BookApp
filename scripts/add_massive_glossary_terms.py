def add_more_terms():
    config_path = Path("config/glossary.json")
    data = json.loads(config_path.read_text(encoding="utf-8"))
    terms = data.get("terms", {})

    tech = terms.get("technical", {})
    lit = terms.get("literary", {})
    gen = terms.get("general", {})

    print(f"Current technical: {len(tech)}")
    print(f"Current literary:  {len(lit)}")
    print(f"Current general:   {len(gen)}")

    added_tech = 0
    for k, v in MORE_TECHNICAL.items():
        k_clean = k.strip().lower()
        if k_clean not in tech:
            tech[k_clean] = v
            added_tech += 1

    added_lit = 0
    for k, v in MORE_LITERARY.items():
        k_clean = k.strip().lower()
        if k_clean not in lit:
            lit[k_clean] = v
            added_lit += 1

    added_gen = 0
    for k, v in MORE_GENERAL.items():
        k_clean = k.strip().lower()
        if k_clean not in gen:
            gen[k_clean] = v
            added_gen += 1

    terms["technical"] = tech
    terms["literary"] = lit
    terms["general"] = gen
    data["terms"] = terms

    print("\n--- After Batch 2 ---")
    print(f"Technical: {len(tech)} (+{added_tech})")
    print(f"Literary:  {len(lit)} (+{added_lit})")
    print(f"General:   {len(gen)} (+{added_gen})")
    print(f"Total:     {len(tech) + len(lit) + len(gen)}")

    config_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print("Saved to config/glossary.json!")


if __name__ == "__main__":
    add_more_terms()
