def expand_glossary():
    config_path = Path("config/glossary.json")
    if not config_path.exists():
        raise FileNotFoundError("config/glossary.json not found!")

    data = json.loads(config_path.read_text(encoding="utf-8"))
    terms = data.get("terms", {})

    tech_existing = terms.get("technical", {})
    lit_existing = terms.get("literary", {})
    gen_existing = terms.get("general", {})

    print(f"Existing technical terms: {len(tech_existing)}")
    print(f"Existing literary terms:  {len(lit_existing)}")
    print(f"Existing general terms:   {len(gen_existing)}")
    print(f"Existing total terms:     {len(tech_existing) + len(lit_existing) + len(gen_existing)}")

    # Add new terms (case-insensitive deduplication)
    added_tech = 0
    for k, v in NEW_TECHNICAL.items():
        k_clean = k.strip().lower()
        if k_clean not in tech_existing:
            tech_existing[k_clean] = v
            added_tech += 1

    added_lit = 0
    for k, v in NEW_LITERARY.items():
        k_clean = k.strip().lower()
        if k_clean not in lit_existing:
            lit_existing[k_clean] = v
            added_lit += 1

    added_gen = 0
    for k, v in NEW_GENERAL.items():
        k_clean = k.strip().lower()
        if k_clean not in gen_existing:
            gen_existing[k_clean] = v
            added_gen += 1

    terms["technical"] = tech_existing
    terms["literary"] = lit_existing
    terms["general"] = gen_existing
    data["terms"] = terms

    total_new = len(tech_existing) + len(lit_existing) + len(gen_existing)
    print("\n--- Expansion Results ---")
    print(f"Technical: {len(tech_existing)} terms (+{added_tech})")
    print(f"Literary:  {len(lit_existing)} terms (+{added_lit})")
    print(f"General:   {len(gen_existing)} terms (+{added_gen})")
    print(f"Total:     {total_new} terms")

    # Atomic write
    config_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nSuccessfully updated {config_path}!")


if __name__ == "__main__":
    expand_glossary()
